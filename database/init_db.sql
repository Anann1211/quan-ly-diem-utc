-- 2. CREATE TABLES

-- Bảng Khoa / Viện
CREATE TABLE KHOA (
    MA_KHOA VARCHAR2(20) PRIMARY KEY,
    TEN_KHOA NVARCHAR2(100) NOT NULL
);

-- Bảng Ngành học
CREATE TABLE NGANH (
    MA_NGANH VARCHAR2(20) PRIMARY KEY,
    TEN_NGANH NVARCHAR2(100) NOT NULL,
    MA_KHOA VARCHAR2(20) REFERENCES KHOA(MA_KHOA) ON DELETE CASCADE
);

-- Bảng Lớp chuyên ngành
CREATE TABLE LOP_CHUYEN_NGANH (
    MA_LOP VARCHAR2(20) PRIMARY KEY,
    TEN_LOP NVARCHAR2(100) NOT NULL,
    KHOA_HOC NUMBER(4) NOT NULL,
    MA_NGANH VARCHAR2(20) REFERENCES NGANH(MA_NGANH) ON DELETE CASCADE
);

-- Bảng Tài khoản người dùng
CREATE TABLE TAI_KHOAN (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TEN_DANG_NHAP VARCHAR2(50) UNIQUE NOT NULL,
    MAT_KHAU VARCHAR2(255) NOT NULL,
    VAI_TRO VARCHAR2(20) NOT NULL CHECK (VAI_TRO IN ('ADMIN', 'GIANG_VIEN', 'SINH_VIEN')),
    HO_TEN NVARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100),
    SO_DIEN_THOAI VARCHAR2(20),
    TRANG_THAI NUMBER(1) DEFAULT 1
);

-- Bảng Giảng viên
CREATE TABLE GIANG_VIEN (
    MA_GV VARCHAR2(20) PRIMARY KEY,
    HO_TEN NVARCHAR2(100) NOT NULL,
    HOC_HAM_HOC_VI NVARCHAR2(50),
    EMAIL VARCHAR2(100),
    DIEN_THOAI VARCHAR2(20),
    MA_KHOA VARCHAR2(20) REFERENCES KHOA(MA_KHOA),
    TAI_KHOAN_ID NUMBER REFERENCES TAI_KHOAN(ID) ON DELETE SET NULL
);

-- Bảng Sinh viên
CREATE TABLE SINH_VIEN (
    MA_SV VARCHAR2(20) PRIMARY KEY,
    HO_TEN NVARCHAR2(100) NOT NULL,
    NGAY_SINH DATE,
    GIOI_TINH NVARCHAR2(10),
    QUE_QUAN NVARCHAR2(100),
    MA_LOP VARCHAR2(20) REFERENCES LOP_CHUYEN_NGANH(MA_LOP),
    TAI_KHOAN_ID NUMBER REFERENCES TAI_KHOAN(ID) ON DELETE SET NULL
);

-- Bảng Môn học
CREATE TABLE MON_HOC (
    MA_MON VARCHAR2(20) PRIMARY KEY,
    TEN_MON NVARCHAR2(100) NOT NULL,
    SO_TIN_CHI NUMBER(2) NOT NULL,
    TY_LE_CC NUMBER(4, 2) DEFAULT 0.10,
    TY_LE_GK NUMBER(4, 2) DEFAULT 0.20,
    TY_LE_THI NUMBER(4, 2) DEFAULT 0.70,
    LOAI_MON VARCHAR2(20) DEFAULT 'TIN_CHI' CHECK (LOAI_MON IN ('TIN_CHI', 'DIEU_KIEN'))
);

-- Bảng Học kỳ
CREATE TABLE HOC_KY (
    MA_HOC_KY VARCHAR2(20) PRIMARY KEY,
    TEN_HOC_KY NVARCHAR2(50) NOT NULL,
    NAM_HOC VARCHAR2(20) NOT NULL,
    TRANG_THAI VARCHAR2(20) DEFAULT 'MO' CHECK (TRANG_THAI IN ('MO', 'KHOA')),
    DANG_HOAT_DONG NUMBER(1) DEFAULT 1
);

-- Bảng Lớp học phần
CREATE TABLE LOP_HOC_PHAN (
    MA_LHP VARCHAR2(30) PRIMARY KEY,
    TEN_LHP NVARCHAR2(100) NOT NULL,
    MA_MON VARCHAR2(20) REFERENCES MON_HOC(MA_MON),
    MA_HOC_KY VARCHAR2(20) REFERENCES HOC_KY(MA_HOC_KY),
    MA_GV VARCHAR2(20) REFERENCES GIANG_VIEN(MA_GV),
    PHONG_HOC VARCHAR2(50),
    SI_SO NUMBER(3) DEFAULT 0,
    TRANG_THAI_DIEM VARCHAR2(20) DEFAULT 'DRAFT' CHECK (TRANG_THAI_DIEM IN ('DRAFT', 'SUBMITTED', 'PUBLISHED'))
);

-- Bảng Điểm sinh viên theo Lớp học phần
CREATE TABLE BANG_DIEM (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MA_LHP VARCHAR2(30) REFERENCES LOP_HOC_PHAN(MA_LHP) ON DELETE CASCADE,
    MA_SV VARCHAR2(20) REFERENCES SINH_VIEN(MA_SV) ON DELETE CASCADE,
    DIEM_CC NUMBER(4, 2),
    DIEM_GK NUMBER(4, 2),
    DIEM_THI NUMBER(4, 2),
    DIEM_TK_10 NUMBER(4, 2),
    DIEM_CHU VARCHAR2(5),
    DIEM_THANG_4 NUMBER(3, 2),
    KET_QUA VARCHAR2(20),
    GHI_CHU NVARCHAR2(255),
    CONSTRAINT UQ_LHP_SV UNIQUE (MA_LHP, MA_SV)
);

-- Bảng Đơn phúc khảo
CREATE TABLE PHUC_KHAO (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BANG_DIEM_ID NUMBER REFERENCES BANG_DIEM(ID) ON DELETE CASCADE,
    MA_SV VARCHAR2(20) REFERENCES SINH_VIEN(MA_SV) ON DELETE CASCADE,
    LY_DO NVARCHAR2(500) NOT NULL,
    DIEM_THI_CU NUMBER(4, 2),
    DIEM_THI_MOI NUMBER(4, 2),
    TRANG_THAI VARCHAR2(20) DEFAULT 'PENDING' CHECK (TRANG_THAI IN ('PENDING', 'APPROVED', 'REJECTED')),
    NGAY_NOP TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    NGAY_XU_LY TIMESTAMP,
    GHI_CHU NVARCHAR2(500),
    NGUOI_XU_LY VARCHAR2(50)
);

-- Bảng Lịch sử điều chỉnh điểm (Audit Log)
CREATE TABLE LICHSU_SUA_DIEM (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BANG_DIEM_ID NUMBER REFERENCES BANG_DIEM(ID) ON DELETE CASCADE,
    NGUOI_SUA VARCHAR2(50) NOT NULL,
    THOI_GIAN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DIEM_CU NVARCHAR2(200),
    DIEM_MOI NVARCHAR2(200),
    LY_DO NVARCHAR2(500) NOT NULL
);

